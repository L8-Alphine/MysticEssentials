/**
 * S2: can a plain block become a crate by swapping it for a generated look-alike
 * BlockType that carries a {@code Use} interaction?
 *
 * <p>The variant is {@code {"Parent": <original>, "Interactions": {"Use": ...}}},
 * decoded with {@code AssetStore.decode} (which resolves the parent) and either
 * registered live with {@code loadAssets} or persisted with
 * {@code writeAssetToDisk} into a directory pack under {@code mods/}, so it loads
 * at boot before any chunk that contains it. The swap keeps the block's rotation
 * and filler through {@code BlockOperations.setBlock}.</p>
 */
final class S2VariantSpike {

    static final String SUFFIX = "_LBSpikeCrate";
    private static final String PACK_FOLDER = "LootBoxSpikeGenerated";
    /** Generated files land in {@code Server/Item/Block/Blocks/<this>/}. */
    private static final String STORE_SUBFOLDER = "LootBoxSpike";
    private static final String BLOCK_STORE_PATH = "Server/Item/Block/Blocks";
    private static final double REACH = 10.0;
    private static final String PACK_MANIFEST = """
            {
                "Group": "org.hyzionstudios",
                "Name": "LootBoxSpikeGenerated",
                "Version": "0.1.0",
                "ServerVersion": ">=0.7.2 <0.8.0",
                "Description": "DEV ONLY. Block variants generated by the LootBox S2 spike.",
                "Authors": [ { "Name": "Alphine" } ]
            }
            """;

    record Swap(String world, int x, int y, int z, String originalKey, String variantKey, int rotation, int filler) {

        String position() {
            return world + " " + x + "," + y + "," + z;
        }
    }

    private record Target(World world, ChunkStore chunkStore, Ref<ChunkStore> section, int x, int y, int z,
            int id, BlockType type, int rotation, int filler) {
    }

    private final SpikeLog log;
    private final Path dataDir;
    private final Path swapsFile;
    private final Map<String, Swap> swaps = new ConcurrentHashMap<>();

    S2VariantSpike(SpikeLog log, Path dataDir) {
        this.log = log;
        this.dataDir = dataDir;
        this.swapsFile = dataDir.resolve("s2-swaps.tsv");
        loadSwaps();
    }

    /** @return the swap recorded at that block, or {@code null}. */
    Swap swapAt(String world, int x, int y, int z) {
        return swaps.get(key(world, x, y, z));
    }

    // ----- Commands (all on the player's world thread) ------------------------

    void look(PlayerRef player, Ref<EntityStore> ref, Store<EntityStore> store) {
        Target target = target(ref, store);
        if (target == null) {
            log.line("S6", "look raycast: no block within " + (int) REACH + " blocks");
            tell(player, "No block within " + (int) REACH + " blocks.");
            return;
        }
        String text = describe(target);
        log.line("S6", "look raycast hit " + text);
        tell(player, "Raycast hit " + text);
    }

    void makeVariant(PlayerRef player, Ref<EntityStore> ref, Store<EntityStore> store, Persist persist,
            String rootOverride) {
        Target target = target(ref, store);
        if (target == null) {
            tell(player, "Look at a block within " + (int) REACH + " blocks first.");
            return;
        }
        String originalKey = target.type().getId();
        if (originalKey.endsWith(SUFFIX)) {
            tell(player, "That block is already a spike variant.");
            return;
        }
        log.line("S2", "variant requested for " + describe(target) + " persist=" + persist
                + (rootOverride == null ? "" : " rootOverride=" + rootOverride));
        BlockType variant;
        try {
            variant = registerVariant(originalKey, persist, rootOverride);
        } catch (Throwable t) {
            log.line("S2", "FAIL registering " + originalKey + SUFFIX + ": " + t);
            tell(player, "Registering the variant failed: " + t);
            return;
        }
        int index = BlockType.getAssetMap().getIndex(variant.getId());
        boolean pass = swap(target, variant, index);
        tell(player, (pass ? "Swapped " : "Swap FAILED for ") + originalKey + " -> " + variant.getId()
                + ". Now use the block: the probe should report UseBlockEvent.Pre and cancel it.");
    }

    void restore(PlayerRef player, Ref<EntityStore> ref, Store<EntityStore> store) {
        Target target = target(ref, store);
        Swap swap = target == null ? null : swapAt(target.world().getName(), target.x(), target.y(), target.z());
        if (swap == null) {
            tell(player, "Look at a block the spike swapped.");
            return;
        }
        int originalIndex = BlockType.getAssetMap().getIndex(swap.originalKey());
        BlockType original = originalIndex == AssetMapWithIndexes.NOT_FOUND ? null
                : BlockType.getAssetMap().getAsset(originalIndex);
        if (original == null) {
            log.line("S2", "FAIL restore: original " + swap.originalKey() + " is no longer registered");
            tell(player, "The original block type is gone.");
            return;
        }
        BlockOperations.setBlock(target.chunkStore(), target.section(), target.x(), target.y(), target.z(),
                originalIndex, original, swap.rotation(), swap.filler(), SetBlockSettings.NO_SEND_PARTICLES);
        Target after = at(target.world(), target.x(), target.y(), target.z());
        boolean pass = after != null && after.id() == originalIndex && after.rotation() == swap.rotation();
        log.line("S2", (pass ? "PASS" : "FAIL") + " restore at " + swap.position() + " -> "
                + (after == null ? "?" : after.type().getId()) + " rotation "
                + (after == null ? "?" : after.rotation()));
        if (pass) {
            swaps.remove(key(swap.world(), swap.x(), swap.y(), swap.z()));
            saveSwaps();
        }
        tell(player, pass ? "Restored " + swap.originalKey() + "." : "Restore FAILED.");
    }

    /** Checks every recorded swap in the player's world whose chunk is loaded. */
    void verify(PlayerRef player, World world) {
        int checked = 0;
        for (Swap swap : List.copyOf(swaps.values())) {
            if (!swap.world().equals(world.getName())) {
                continue;
            }
            Target now = at(world, swap.x(), swap.y(), swap.z());
            if (now == null) {
                log.line("S2", "verify " + swap.position() + ": chunk not loaded");
                continue;
            }
            checked++;
            boolean pass = now.type().getId().equalsIgnoreCase(swap.variantKey()) && !now.type().isUnknown()
                    && now.rotation() == swap.rotation() && hasUse(now.type());
            log.line("S2", (pass ? "PASS" : "FAIL") + " verify " + swap.position() + ": key=" + now.type().getId()
                    + " unknown=" + now.type().isUnknown() + " rotation=" + now.rotation() + " (expected "
                    + swap.rotation() + ") hasUse=" + hasUse(now.type()));
        }
        tell(player, "Checked " + checked + " loaded swap(s); results are in " + log.file().getFileName());
    }

    // ----- Boot report and headless autotest ----------------------------------

    void reportGeneratedPackOnBoot() {
        log.line("S2", "boot: BlockType map holds " + BlockType.getAssetMap().getNextIndex() + " indexes");
        Path packDir = modsDirectory().resolve(PACK_FOLDER);
        if (!Files.isDirectory(packDir)) {
            log.line("S2", "boot: no generated pack yet at " + packDir);
            return;
        }
        AssetPack pack = findGeneratedPack(packDir);
        log.line("S2", "boot: generated pack folder present; registered at boot=" + (pack != null)
                + (pack == null ? " (external packs follow DefaultModsEnabled and the mod config)"
                        : ", immutable=" + pack.isImmutable()));
        Path variantsDir = packDir.resolve(BLOCK_STORE_PATH).resolve(STORE_SUBFOLDER);
        if (Files.isDirectory(variantsDir)) {
            try (Stream<Path> files = Files.list(variantsDir)) {
                files.filter(file -> file.getFileName().toString().endsWith(".json")).forEach(file -> {
                    String key = file.getFileName().toString().replaceFirst("\\.json$", "");
                    int index = BlockType.getAssetMap().getIndex(key);
                    BlockType type = index == AssetMapWithIndexes.NOT_FOUND ? null
                            : BlockType.getAssetMap().getAsset(index);
                    String useRoot = type == null ? null : useRoot(type);
                    boolean rootExists = rootExists(useRoot);
                    boolean pass = type != null && !type.isUnknown() && rootExists;
                    log.line("S2", (pass ? "PASS" : "FAIL") + " boot: persisted variant " + key + " ("
                            + fileStyle(file) + ") loaded=" + (type != null) + " unknown="
                            + (type != null && type.isUnknown()) + " use=" + useRoot + " rootExists=" + rootExists);
                });
            } catch (IOException e) {
                log.line("S2", "boot: could not list " + variantsDir + ": " + e);
            }
        }
        if (!swaps.isEmpty()) {
            log.line("S2", "boot: " + swaps.size() + " recorded swap(s); run /lbspike s2 verify near them.");
        }
    }

    /**
     * The server-side half of S2, with no player: picks plain blocks from the
     * registry and registers one variant per persistence mode, reporting what each
     * inherited. The swap and the in-world Use need a player.
     */
    void autotest() {
        log.line("S2", "autotest: start");
        Persist[] modes = Persist.values();
        List<String> candidates = plainCandidates(modes.length);
        log.line("S2", "autotest: plain block candidates " + candidates);
        if (candidates.isEmpty()) {
            log.line("S2", "FAIL autotest: no plain cube block without a Use interaction found");
            return;
        }
        for (int i = 0; i < Math.min(modes.length, candidates.size()); i++) {
            Persist mode = modes[i];
            String original = candidates.get(i);
            try {
                registerVariant(original, mode, null);
                if (mode == Persist.NONE) {
                    log.line("S2", "PASS autotest: live variant of " + original);
                } else {
                    Path file = variantFile(original + SUFFIX);
                    log.line("S2", (Files.isRegularFile(file) ? "PASS" : "FAIL") + " autotest: " + mode
                            + " variant of " + original + " written (" + fileStyle(file)
                            + "); restart and read the boot report.");
                }
            } catch (Throwable t) {
                log.line("S2", "FAIL autotest " + mode + " variant of " + original + ": " + t);
            }
        }
        log.line("S2", "autotest: done");
    }

    /** How a variant is persisted. */
    enum Persist {
        /** Live only: gone after a restart. */
        NONE,
        /** {@code AssetStore.writeAssetToDisk}: the engine writes the fully resolved asset. */
        ENGINE,
        /** Our own minimal {@code Parent} + inline {@code Use} document, loaded the way boot loads it. */
        RAW
    }

    // ----- Registration and swap ----------------------------------------------

    private BlockType registerVariant(String originalKey, Persist persist, String rootOverride) throws Exception {
        String variantKey = originalKey + SUFFIX;
        BsonDocument document = new BsonDocument("Parent", new BsonString(originalKey));
        BsonDocument interactions = new BsonDocument();
        if (rootOverride != null && !rootOverride.isBlank()) {
            interactions.put("Use", new BsonString(rootOverride));
        } else {
            interactions.put("Use", BsonDocument.parse(
                    "{\"Interactions\": [{\"Type\": \"" + SpikeUseInteraction.TYPE_ID + "\"}]}"));
        }
        document.put("Interactions", interactions);

        var store = AssetRegistry.getAssetStore(BlockType.class);
        long started = System.nanoTime();
        switch (persist) {
            case ENGINE -> {
                AssetPack pack = generatedPack();
                // writeAssetToDisk writes with Files.writeString and never creates folders.
                Files.createDirectories(variantFile(variantKey).getParent());
                BlockType decoded = store.decode(pack.getName(), variantKey, document);
                store.writeAssetToDisk(pack, Map.of(Path.of(STORE_SUBFOLDER, variantKey + ".json"), decoded),
                        AssetUpdateQuery.DEFAULT, false);
            }
            case RAW -> {
                AssetPack pack = generatedPack();
                Path file = variantFile(variantKey);
                Files.createDirectories(file.getParent());
                Files.writeString(file, document.toJson(), StandardCharsets.UTF_8);
                store.loadAssetsFromPaths(pack.getName(), List.of(file));
            }
            default -> {
                BlockType decoded = store.decode(DefaultAssetMap.DEFAULT_PACK_KEY, variantKey, document);
                store.loadAssets(DefaultAssetMap.DEFAULT_PACK_KEY, List.of(decoded), AssetUpdateQuery.DEFAULT, true);
            }
        }
        long millis = (System.nanoTime() - started) / 1_000_000L;

        int index = BlockType.getAssetMap().getIndex(variantKey);
        BlockType loaded = index == AssetMapWithIndexes.NOT_FOUND ? null : BlockType.getAssetMap().getAsset(index);
        if (loaded == null) {
            throw new IllegalStateException(variantKey + " is not in the BlockType map after loading");
        }
        BlockType parent = BlockType.getAssetMap().getAsset(BlockType.getAssetMap().getIndex(originalKey));
        String useRoot = useRoot(loaded);
        log.line("S2", "registered " + variantKey + " (persist=" + persist + ", " + millis + " ms, index "
                + index + ") use=" + useRoot + " rootExists=" + rootExists(useRoot)
                + " | inherits from " + originalKey
                + ": drawType=" + same(parent.getDrawType(), loaded.getDrawType())
                + " customModel=" + same(parent.getCustomModel(), loaded.getCustomModel())
                + " material=" + same(parent.getMaterial(), loaded.getMaterial())
                + " opacity=" + same(parent.getOpacity(), loaded.getOpacity())
                + " hitbox=" + same(parent.getHitboxType(), loaded.getHitboxType())
                + " textures=" + same(count(parent.getTextures()), count(loaded.getTextures()))
                + " gathering=" + same(parent.getGathering() != null, loaded.getGathering() != null));
        return loaded;
    }

    private boolean swap(Target target, BlockType variant, int variantIndex) {
        boolean changed = BlockOperations.setBlock(target.chunkStore(), target.section(),
                target.x(), target.y(), target.z(), variantIndex, variant, target.rotation(), target.filler(),
                SetBlockSettings.NO_SEND_PARTICLES);
        Target after = at(target.world(), target.x(), target.y(), target.z());
        boolean pass = after != null && after.id() == variantIndex && after.rotation() == target.rotation();
        String position = target.world().getName() + " " + target.x() + "," + target.y() + "," + target.z();
        log.line("S2", (pass ? "PASS" : "FAIL") + " swap at " + position + " changed=" + changed + " key "
                + target.type().getId() + " -> " + (after == null ? "?" : after.type().getId()) + " rotation "
                + target.rotation() + " -> " + (after == null ? "?" : after.rotation()));
        if (pass) {
            Swap swap = new Swap(target.world().getName(), target.x(), target.y(), target.z(),
                    target.type().getId(), variant.getId(), target.rotation(), target.filler());
            swaps.put(key(swap.world(), swap.x(), swap.y(), swap.z()), swap);
            saveSwaps();
        }
        return pass;
    }

    // ----- Generated pack -----------------------------------------------------

    private AssetPack generatedPack() throws IOException {
        Path packDir = modsDirectory().resolve(PACK_FOLDER);
        Path manifestPath = packDir.resolve("manifest.json");
        if (!Files.isRegularFile(manifestPath)) {
            Files.createDirectories(packDir);
            Files.writeString(manifestPath, PACK_MANIFEST, StandardCharsets.UTF_8);
            log.line("S2", "created generated pack folder " + packDir);
        }
        AssetPack pack = findGeneratedPack(packDir);
        if (pack == null) {
            PluginManifest manifest = readManifest(manifestPath);
            String packId = new PluginIdentifier(manifest).toString();
            if (!AssetModule.get().registerPack(packId, packDir, manifest, AssetPack.PackSource.MODS)) {
                throw new IOException("registerPack refused " + packId);
            }
            pack = AssetModule.get().getAssetPack(packId);
            log.line("S2", "registered generated pack " + packId + " at runtime");
        }
        if (pack == null) {
            throw new IOException("generated pack missing after registerPack");
        }
        if (pack.isImmutable()) {
            throw new IOException("generated pack " + pack.getName() + " is immutable");
        }
        return pack;
    }

    private static AssetPack findGeneratedPack(Path packDir) {
        try {
            PluginManifest manifest = readManifest(packDir.resolve("manifest.json"));
            return AssetModule.get().getAssetPack(new PluginIdentifier(manifest).toString());
        } catch (IOException | RuntimeException e) {
            return null;
        }
    }

    private static PluginManifest readManifest(Path manifestPath) throws IOException {
        try (Reader reader = Files.newBufferedReader(manifestPath, StandardCharsets.UTF_8)) {
            RawJsonReader json = new RawJsonReader(reader, RawJsonReader.READ_BUFFER.get());
            return PluginManifest.CODEC.decodeJson(json, ExtraInfo.THREAD_LOCAL.get());
        }
    }

    /** The folder our own jar was loaded from: the server's mods folder. */
    private Path modsDirectory() {
        for (AssetPack pack : AssetModule.get().getAssetPacks()) {
            Path location = pack.getPackLocation();
            if (location != null && location.getFileName() != null
                    && location.getFileName().toString().startsWith("MysticLootBoxSpikes")) {
                return location.toAbsolutePath().getParent();
            }
        }
        return dataDir.toAbsolutePath().getParent();
    }

    // ----- Helpers ------------------------------------------------------------

    private static List<String> plainCandidates(int wanted) {
        List<String> preferred = new ArrayList<>();
        List<String> others = new ArrayList<>();
        int next = BlockType.getAssetMap().getNextIndex();
        for (int i = 1; i < next; i++) {
            BlockType type = BlockType.getAssetMap().getAsset(i);
            if (type == null || type.isUnknown() || hasUse(type) || type.getBlockEntity() != null
                    || type.getGathering() == null || !"Cube".equals(String.valueOf(type.getDrawType()))
                    || type.getId().endsWith(SUFFIX) || type.getId().contains("State")) {
                continue;
            }
            String id = type.getId().toLowerCase(Locale.ROOT);
            (id.contains("stone") || id.contains("plank") ? preferred : others).add(type.getId());
        }
        List<String> result = new ArrayList<>(preferred);
        result.addAll(others);
        return result.subList(0, Math.min(wanted, result.size()));
    }

    private static Target target(Ref<EntityStore> ref, Store<EntityStore> store) {
        Vector3i position = TargetUtil.getTargetBlock(ref, REACH, store);
        if (position == null) {
            return null;
        }
        return at(store.getExternalData().getWorld(), position.x, position.y, position.z);
    }

    private static Target at(World world, int x, int y, int z) {
        ChunkStore chunkStore = world.getChunkStore();
        Ref<ChunkStore> section = chunkStore.getChunkSectionReferenceAtBlock(x, y, z);
        if (section == null || !section.isValid()) {
            return null;
        }
        BlockSection blocks = chunkStore.getStore().getComponent(section, BlockSection.getComponentType());
        if (blocks == null) {
            return null;
        }
        int id = blocks.get(x, y, z);
        BlockType type = BlockType.getAssetMap().getAsset(id);
        if (type == null) {
            return null;
        }
        return new Target(world, chunkStore, section, x, y, z, id, type,
                blocks.getRotationIndex(x, y, z), blocks.getFiller(x, y, z));
    }

    static boolean hasUse(BlockType type) {
        return useRoot(type) != null;
    }

    private static String useRoot(BlockType type) {
        Map<InteractionType, String> interactions = type.getInteractions();
        return interactions == null ? null : interactions.get(InteractionType.Use);
    }

    /** Looks the root up without creating the "unknown" placeholder that getRootInteractionOrUnknown would. */
    private static boolean rootExists(String rootId) {
        return rootId != null && RootInteraction.getAssetMap().getIndex(rootId) != AssetMapWithIndexes.NOT_FOUND;
    }

    private Path variantFile(String variantKey) {
        return modsDirectory().resolve(PACK_FOLDER).resolve(BLOCK_STORE_PATH).resolve(STORE_SUBFOLDER)
                .resolve(variantKey + ".json");
    }

    /** "inherits (Parent)" for our raw documents, "flattened" for writeAssetToDisk output. */
    private static String fileStyle(Path file) {
        try {
            String json = Files.readString(file, StandardCharsets.UTF_8);
            return (json.contains("\"Parent\"") ? "inherits via Parent" : "flattened, no Parent") + ", "
                    + json.length() + " chars";
        } catch (IOException e) {
            return "unreadable: " + e.getMessage();
        }
    }

    private static String describe(Target target) {
        BlockType type = target.type();
        return target.x() + "," + target.y() + "," + target.z() + " key=" + type.getId() + " rotation="
                + target.rotation() + " filler=" + target.filler() + " hasUse=" + hasUse(type)
                + " hasGathering=" + (type.getGathering() != null) + " unknown=" + type.isUnknown();
    }

    private static String same(Object parent, Object child) {
        return Objects.equals(parent, child) ? "same" : "DIFFERS(" + parent + " vs " + child + ")";
    }

    private static int count(Object[] values) {
        return values == null ? 0 : values.length;
    }

    private static String key(String world, int x, int y, int z) {
        return world + "|" + x + "|" + y + "|" + z;
    }

    private static void tell(PlayerRef player, String text) {
        player.sendMessage(Message.raw("[LBSpike] " + text));
    }

    private void loadSwaps() {
        if (!Files.isRegularFile(swapsFile)) {
            return;
        }
        try {
            for (String line : Files.readAllLines(swapsFile, StandardCharsets.UTF_8)) {
                String[] f = line.split("\t");
                if (f.length == 8) {
                    Swap swap = new Swap(f[0], Integer.parseInt(f[1]), Integer.parseInt(f[2]),
                            Integer.parseInt(f[3]), f[4], f[5], Integer.parseInt(f[6]), Integer.parseInt(f[7]));
                    swaps.put(key(swap.world(), swap.x(), swap.y(), swap.z()), swap);
                }
            }
        } catch (IOException | RuntimeException e) {
            log.line("S2", "could not read " + swapsFile + ": " + e);
        }
    }

    private void saveSwaps() {
        StringBuilder out = new StringBuilder();
        for (Swap s : swaps.values()) {
            out.append(s.world()).append('\t').append(s.x()).append('\t').append(s.y()).append('\t')
                    .append(s.z()).append('\t').append(s.originalKey()).append('\t').append(s.variantKey())
                    .append('\t').append(s.rotation()).append('\t').append(s.filler()).append('\n');
        }
        try {
            Files.createDirectories(swapsFile.getParent());
            Files.writeString(swapsFile, out.toString(), StandardCharsets.UTF_8);
        } catch (IOException e) {
            log.line("S2", "could not write " + swapsFile + ": " + e);
        }
    }
}
